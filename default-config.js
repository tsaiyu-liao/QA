// 把存好的設定補上預設值（之後若新增欄位，舊設定也能正常顯示）
function withDefaults(saved, base = DEFAULT_CONFIG) {
  if (!saved || typeof saved !== "object" || Array.isArray(saved)) return JSON.parse(JSON.stringify(base));
  const out = {};
  for (const key of Object.keys(base)) {
    const b = base[key], s = saved[key];
    if (s === undefined) out[key] = JSON.parse(JSON.stringify(b));
    else if (b && typeof b === "object" && !Array.isArray(b)) out[key] = withDefaults(s, b);
    else out[key] = s;
  }
  return out;
}
